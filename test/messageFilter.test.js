test('блокирует контакты, сайты, мессенджеры, реквизиты и телефоны', () => {
  const missed = MUST_BLOCK.filter((m) => !checkMessage(m).blocked);
  assert.deepStrictEqual(missed, [], 'Пропущены: ' + missed.join(' | '));
});

test('не мешает обычной переписке', () => {
  const blocked = MUST_PASS.filter((m) => checkMessage(m).blocked).map((m) => `${m} → ${checkMessage(m).code}`);
  assert.deepStrictEqual(blocked, [], 'Ложно заблокированы: ' + blocked.join(' | '));
});

test('номер «в столбик» по нескольким сообщениям', () => {
  assert.strictEqual(checkConversation('900', ['7']).blocked, false, '7, 900 — ещё рано');
  assert.strictEqual(checkConversation('200', ['7', '900']).blocked, true, '7, 900, 200 — блок');
  assert.strictEqual(checkConversation('двести', ['семь', 'девятьсот']).blocked, true, 'словами');
  assert.strictEqual(checkConversation('123', ['8', '9', '12']).blocked, true, '8, 9, 12, 123');
  assert.strictEqual(checkConversation('45 67', ['+7', '900 123']).blocked, true);
  assert.strictEqual(checkConversation('900 12', ['вот мой номер']).blocked, true, 'номер после «вот мой номер»');
  assert.strictEqual(checkConversation('vasyapro', ['мой ник']).blocked, true, 'ник следующим сообщением');
  assert.strictEqual(checkConversation('пей', ['фан']).blocked, true, 'название по частям');
  // обычный торг не блокируется
  assert.strictEqual(checkConversation('2000', ['Цена 1500?']).blocked, false);
  assert.strictEqual(checkConversation('А за 6000 отдадите?', ['Сколько скинов?', '47']).blocked, false);
  assert.strictEqual(checkConversation('7', ['900']).blocked, false);
});
